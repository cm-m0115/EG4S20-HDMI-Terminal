// Passive observer; no connection drives the audio datapath.
// 128x11 history, 228x7 double-bank nodes, one shared multiply/divide engine.
module recovery_audio_visualizer(
 input wire clk,rst,vs,input wire audio_valid,input wire [23:0] audio_left,
 input wire enable,input wire [15:0] source_tag,input wire [8:0] query_index,
 output wire signed [7:0] wave_min,wave_max,
 output reg [7:0] average,peak,output reg [6:0] newest_index,
 output wire [3:0] wave_fraction,
 input wire de,output reg [9:0] front_q4,back_q4,output wire mountain_valid
);
localparam [4:0] IDLE=0,READ=1,WAIT_READ=2,ACC=3,NORMALIZE=4,HAVE_SMOOTH=5,
 LERP_A=6,LERP_B=7,RESAMPLE_DONE=8,MAP_PREP=9,MAP_PRODUCT=10,
 MAP_DIV=11,HEIGHT_DONE=12,WRITE_NODE=13,PF_READ=14,PF_WAIT=15,
 PF_CAPTURE=16,COMMIT=17,DIVIDE=18;
(* ram_style="bram" *) reg [10:0] history[0:127];
(* ram_style="bram" *) reg [6:0] nodes[0:227];
reg [10:0] history_q;
reg [6:0] node_q;
reg [6:0] head,snapshot_head;
reg [7:0] history_count;reg [5:0] snapshot_missing;
reg [9:0] sample_count;
reg [17:0] absolute_sum;
reg [8:0] absolute_peak;
reg [10:0] envelope;
reg [15:0] held_tag; // Any tag change immediately invalidates table/state via source_valid.
reg held_enable,previous_vs,half_frame,sample_seen,blank_window;
reg [10:0] silence_attenuation,snapshot_attenuation;
reg table_valid,active_bank,build_bank,layer;
reg [4:0] state,div_return;
reg [5:0] smooth_index,node_index;
reg [3:0] tap;
reg [16:0] weighted_sum;
reg [10:0] current_smooth,previous_smooth,resampled;
reg [16:0] lerp_sum;
reg [6:0] mapped_value,node_height;
reg [10:0] map_product; // Rounded product /1024; low ten bits can never affect quotient/25.
reg [16:0] div_numerator;
reg [5:0] div_remainder,div_denominator;
wire [10:0] division_result=div_numerator[10:0]; // Restoring division shares dividend/quotient storage.
reg [4:0] div_count;
reg [1:0] prefetch_index;
reg [6:0] pending_f0,pending_f1,pending_b0,pending_b1;
reg [6:0] anchor_f0,anchor_f1,anchor_b0,anchor_b1;
reg [6:0] right_f,right_b,next_f,next_b;
reg signed [7:0] delta_f,delta_b;
reg signed [10:0] accumulator_f,accumulator_b;
reg [13:0] build_cycles,last_build_cycles;
reg build_timeout;
wire source_valid=enable&&held_enable&&source_tag==held_tag;
wire frame_start=previous_vs&&!vs;
wire start_build=frame_start&&!half_frame&&source_valid&&state==IDLE;
wire [8:0] abs_sample=audio_left[23]?9'd256-{1'b0,audio_left[23:16]}:{1'b0,audio_left[23:16]};
wire [17:0] sample_sum=absolute_sum+{9'd0,abs_sample};
wire [11:0] target_wide=sample_sum[17:6];
wire [10:0] target=target_wide>12'd2032 ? 11'd2032:target_wide[10:0];
wire signed [11:0] env_delta=$signed({1'b0,target})-$signed({1'b0,envelope});
wire signed [11:0] env_step=env_delta>=0?(env_delta+12'sd1)>>>1:env_delta>>>3;
wire [10:0] next_envelope=$signed({1'b0,envelope})+env_step;
wire write_bin=audio_valid&&source_valid&&sample_count==10'd1023;
wire signed [7:0] filter_position=$signed({2'b00,smooth_index})+$signed({4'd0,tap})-(layer?8'sd6:8'sd3);
wire [5:0] clamped_position=filter_position<0?6'd0:filter_position>55?6'd55:filter_position[5:0];
wire [6:0] history_address=snapshot_head-7'd56+{1'b0,clamped_position};
wire history_position_valid=clamped_position>=snapshot_missing;
wire [3:0] tap_last=layer?4'd12:4'd6;
wire [3:0] tap_weight=tap<=(layer?6:3)?tap+4'd1:(layer?4'd13:4'd7)-tap;
reg [10:0] multiply_a,multiply_b;
wire [21:0] multiply_result=multiply_a*multiply_b;
wire [16:0] accumulated=weighted_sum+multiply_result[16:0];
wire [6:0] division_trial={div_remainder,div_numerator[16]};
wire [7:0] division_difference={1'b0,division_trial}-{2'b00,div_denominator};
wire division_bit=~division_difference[7]; // One exact subtract supplies result and borrow.
// floor(N/25600) = floor(floor(N/1024)/25). Max other dividend113820 fits17 bits; max divisor56 fits6.
wire [10:0] smoothed_value=layer?division_result:current_smooth;
wire [11:0] fade_difference={1'b0,resampled}-{1'b0,snapshot_attenuation};
wire [10:0] faded_value=fade_difference[11]?11'd0:fade_difference[10:0];
wire [6:0] segment_left_f=query_index[8:3]==0?anchor_f0:right_f;
wire [6:0] segment_right_f=query_index[8:3]==0?anchor_f1:next_f;
wire [6:0] segment_left_b=query_index[8:3]==0?anchor_b0:right_b;
wire [6:0] segment_right_b=query_index[8:3]==0?anchor_b1:next_b;
wire signed [7:0] segment_delta_f=$signed({1'b0,segment_right_f})-$signed({1'b0,segment_left_f});
wire signed [7:0] segment_delta_b=$signed({1'b0,segment_right_b})-$signed({1'b0,segment_left_b});
wire [5:0] lookahead_node=query_index[8:3]<55?query_index[8:3]+6'd2:6'd56;
reg [7:0] node_read_address;
function [7:0] node_address;
 input bank,back_layer;input [5:0] index;
 begin node_address=(bank?8'd114:8'd0)+(back_layer?8'd57:8'd0)+{2'd0,index};end
endfunction
// Exact round-half-up Q10 smoothstep at r=55*i/56, generated by rational arithmetic.
(* ram_style="bram" *) reg [10:0] taper_rom[0:63];
reg [10:0] taper_q;
initial begin
