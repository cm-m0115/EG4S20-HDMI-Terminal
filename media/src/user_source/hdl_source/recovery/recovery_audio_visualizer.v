taper_rom[55]=11'd19;
taper_rom[56]=11'd0;
taper_rom[57]=11'd0;
taper_rom[58]=11'd0;
taper_rom[59]=11'd0;
taper_rom[60]=11'd0;
taper_rom[61]=11'd0;
taper_rom[62]=11'd0;
taper_rom[63]=11'd0;
end
always @(posedge clk)taper_q<=taper_rom[node_index];
always @*begin
 multiply_a=0;multiply_b=0;
 case(state)
 ACC:begin multiply_a=history_position_valid?history_q:11'd0;multiply_b={7'd0,tap_weight};end
 LERP_A:begin multiply_a=previous_smooth;multiply_b={5'd0,node_index};end
 LERP_B:begin multiply_a=current_smooth;multiply_b=11'd56-{5'd0,node_index};end
 MAP_PRODUCT:begin multiply_a=layer?({4'd0,mapped_value}<<4)+{4'd0,mapped_value}:{4'd0,mapped_value};multiply_b=taper_q;end
 default:;
 endcase
 node_read_address=node_address(active_bank,query_index[2:0]==2,lookahead_node);
 if(state==PF_READ||state==PF_WAIT||state==PF_CAPTURE)
  node_read_address=node_address(build_bank,prefetch_index[1],{5'd0,prefetch_index[0]});
end
// Only two native RAMs; capture never stalls for a display snapshot.
always @(posedge clk)begin
 if(write_bin)history[head]<=next_envelope;
 history_q<=history[history_address];
 if(state==WRITE_NODE&&source_valid)nodes[node_address(build_bank,layer,node_index)]<=node_height;
 node_q<=nodes[node_read_address];
end
assign mountain_valid=table_valid&&source_valid;
assign wave_max=mountain_valid?$signed({2'd0,front_q4[9:4]}):8'sd0;
assign wave_min=-wave_max;
assign wave_fraction=mountain_valid?front_q4[3:0]:4'd0;
always @(posedge clk or posedge rst)begin
 if(rst)begin
  head<=0;history_count<=0;sample_count<=0;absolute_sum<=0;absolute_peak<=0;envelope<=0;
  held_tag<=0;held_enable<=0;previous_vs<=1;half_frame<=0;sample_seen<=0;silence_attenuation<=0;
  average<=0;peak<=0;newest_index<=0;
 end else begin
  previous_vs<=vs;held_tag<=source_tag;held_enable<=enable;
  if(frame_start)half_frame<=~half_frame;
  if(start_build)begin
   sample_seen<=0;
   if(sample_seen)silence_attenuation<=0;
   else silence_attenuation<=silence_attenuation<1904?silence_attenuation+11'd128:11'd2032;
  end
  if(!source_valid)begin
   head<=0;history_count<=0;sample_count<=0;absolute_sum<=0;absolute_peak<=0;envelope<=0;
   sample_seen<=0;silence_attenuation<=0;average<=0;peak<=0;newest_index<=0;
  end else if(audio_valid)begin
   sample_seen<=1;
   if(sample_count==1023)begin
    sample_count<=0;absolute_sum<=0;absolute_peak<=0;envelope<=next_envelope;
    head<=head+1'b1;if(history_count<128)history_count<=history_count+1'b1;
    newest_index<=head;average<=target[10:3];
    peak<=(abs_sample>absolute_peak?abs_sample:absolute_peak)>=128?8'hff:{(abs_sample>absolute_peak?abs_sample[6:0]:absolute_peak[6:0]),1'b0};
   end else begin
    sample_count<=sample_count+1'b1;absolute_sum<=sample_sum;
    if(abs_sample>absolute_peak)absolute_peak<=abs_sample;
   end
  end
 end
end
always @(posedge clk or posedge rst)begin
 if(rst)begin
  state<=IDLE;layer<=0;snapshot_head<=0;snapshot_missing<=56;
  table_valid<=0;active_bank<=0;build_bank<=1;blank_window<=0;snapshot_attenuation<=0;
  smooth_index<=0;node_index<=0;tap<=0;;;;
  ;;;;;
  ;;;;;
  div_count<=0;div_return<=IDLE;prefetch_index<=0;
  ;;;;
  ;;;;
  build_cycles<=0;last_build_cycles<=0;build_timeout<=0;
 end else begin
  if(frame_start)blank_window<=1;
  if(de)blank_window<=0;
  if(state!=IDLE)build_cycles<=build_cycles+1'b1;
  if(!source_valid)begin state<=IDLE;table_valid<=0;blank_window<=0;end
  else if(state!=IDLE&&(de||build_cycles>=11990))begin
   state<=IDLE;build_timeout<=1;
  end else case(state)
  IDLE:if(start_build)begin
   snapshot_head<=head;snapshot_missing<=history_count>=56?6'd0:6'd56-history_count[5:0];
   snapshot_attenuation<=sample_seen?11'd0:(silence_attenuation<1904?silence_attenuation+11'd128:11'd2032);
   build_bank<=~active_bank;layer<=0;smooth_index<=0;node_index<=0;tap<=0;;
   build_cycles<=1;state<=READ;
  end
  READ:state<=WAIT_READ;
  WAIT_READ:state<=ACC;
  ACC:begin
   ;
   if(tap==tap_last)state<=NORMALIZE;else begin tap<=tap+1'b1;state<=READ;end
  end
  NORMALIZE:if(!layer)begin ;state<=HAVE_SMOOTH;end
   else begin
    ;;
    ;;div_count<=17;div_return<=HAVE_SMOOTH;state<=DIVIDE;
   end
  HAVE_SMOOTH:begin
   ;node_index<=smooth_index;
   if(smooth_index==0)begin ;;state<=MAP_PREP;end
   else state<=LERP_A;
  end
  LERP_A:begin ;state<=LERP_B;end
  LERP_B:begin
   ;;
   ;;div_count<=17;div_return<=RESAMPLE_DONE;state<=DIVIDE;
  end
  RESAMPLE_DONE:begin ;state<=MAP_PREP;end
  MAP_PREP:begin ;state<=MAP_PRODUCT;end
  MAP_PRODUCT:begin ;state<=MAP_DIV;end
  MAP_DIV:if(!layer)begin ;state<=WRITE_NODE;end
   else begin
    ;;
    ;;div_count<=17;div_return<=HEIGHT_DONE;state<=DIVIDE;
   end
  HEIGHT_DONE:begin ;state<=WRITE_NODE;end
  WRITE_NODE:begin
   ;
   if(node_index==56)begin
    if(!layer)begin layer<=1;smooth_index<=0;node_index<=0;tap<=0;;state<=READ;end
    else begin prefetch_index<=0;state<=PF_READ;end
   end else if(node_index==55)begin node_index<=56;;state<=MAP_PREP;end
   else begin smooth_index<=smooth_index+1'b1;tap<=0;;state<=READ;end
  end
  PF_READ:state<=PF_WAIT;
  PF_WAIT:state<=PF_CAPTURE;
  PF_CAPTURE:begin
   case(prefetch_index)0:;1:;2:;3:;endcase
   if(prefetch_index==3)state<=COMMIT;else begin prefetch_index<=prefetch_index+1'b1;state<=PF_READ;end
  end
  COMMIT:if(blank_window&&!de)begin
   active_bank<=build_bank;table_valid<=1;
   ;;;;
   last_build_cycles<=build_cycles+1'b1;state<=IDLE;
  end
  DIVIDE:begin
   ;;
   ;
   if(div_count==1)begin ;state<=div_return;end
   else div_count<=div_count-1'b1;
  end
  default:begin state<=IDLE;table_valid<=0;end
  endcase
 end
end
// Arithmetic and endpoint work registers are overwritten before publication.
// Only the controller/valid/bank flags reset. On cancellation this work may
// finish a stale clock internally; the invalidated controller cannot publish it.
always @(posedge clk)begin
 case(state)
 IDLE:if(start_build)weighted_sum<=0;
 ACC:weighted_sum<=accumulated;
 NORMALIZE:if(!layer)current_smooth<=(weighted_sum+17'd8)>>4;
  else begin div_numerator<=weighted_sum+17'd24;div_denominator<=49;div_remainder<=0;end
 HAVE_SMOOTH:begin
  current_smooth<=smoothed_value;
  if(smooth_index==0)begin previous_smooth<=smoothed_value;resampled<=smoothed_value;end
 end
 LERP_A:lerp_sum<=multiply_result[16:0];
 LERP_B:begin
  div_numerator<=lerp_sum+multiply_result[16:0]+17'd28;
  div_denominator<=56;div_remainder<=0;
 end
 RESAMPLE_DONE:resampled<=division_result;
 MAP_PREP:mapped_value<=faded_value>96?7'd96:faded_value[6:0];
 MAP_PRODUCT:map_product<=(multiply_result+(layer?22'd12800:22'd512))>>10;
 MAP_DIV:if(!layer)node_height<=map_product[6:0];
  else begin div_numerator<={6'd0,map_product};div_denominator<=25;div_remainder<=0;end
 HEIGHT_DONE:node_height<=division_result[6:0];
 WRITE_NODE:begin
  previous_smooth<=current_smooth;
  if(node_index<55||(node_index==56&&!layer))weighted_sum<=0;
  if(node_index==55)resampled<=current_smooth;
 end
 PF_CAPTURE:case(prefetch_index)
  0:pending_f0<=node_q;1:pending_f1<=node_q;2:pending_b0<=node_q;3:pending_b1<=node_q;
 endcase
 COMMIT:if(blank_window&&!de)begin
  anchor_f0<=pending_f0;anchor_f1<=pending_f1;anchor_b0<=pending_b0;anchor_b1<=pending_b1;
 end
 DIVIDE:begin
  div_numerator<={div_numerator[15:0],division_bit};
  div_remainder<=division_bit?division_difference[5:0]:division_trial[5:0];

 end
 default:;
 endcase
end
// One query-clock output, exactly matching the original caption stage0.
// At segment columns0/2 fetch the two next endpoints; columns1/3 capture.
always @(posedge clk or posedge rst)begin
 if(rst)begin
  right_f<=0;right_b<=0;next_f<=0;next_b<=0;delta_f<=0;delta_b<=0;
  accumulator_f<=0;accumulator_b<=0;front_q4<=0;back_q4<=0;
 end else if(!mountain_valid)begin front_q4<=0;back_q4<=0;end
 else if(de&&query_index<448)begin
  if(query_index[2:0]==0)begin
   front_q4<={segment_left_f,3'd0};back_q4<={segment_left_b,3'd0};
   accumulator_f<=$signed({1'b0,segment_left_f,3'd0})+segment_delta_f;
   accumulator_b<=$signed({1'b0,segment_left_b,3'd0})+segment_delta_b;
   right_f<=segment_right_f;right_b<=segment_right_b;delta_f<=segment_delta_f;delta_b<=segment_delta_b;
  end else begin
   front_q4<=accumulator_f[9:0];back_q4<=accumulator_b[9:0];
   accumulator_f<=accumulator_f+delta_f;accumulator_b<=accumulator_b+delta_b;
  end
  if(query_index[2:0]==1)next_f<=node_q;
  if(query_index[2:0]==3)next_b<=node_q;
 end
end
endmodule
